def call_gemini_json(prompt):
    """One Gemini call, JSON mode, with one retry on a bad response."""
    require_key()
    body = {
        "contents": [{"parts": [{"text": prompt}]}],
        "generationConfig": {"temperature": 0.7, "responseMimeType": "application/json"},
    }
    for attempt in (1, 2):
        response = httpx.post(
            f"{config.GEMINI_API_BASE}/models/{config.GEMINI_MODEL}:generateContent",
            headers={"x-goog-api-key": config.GEMINI_API_KEY},
            json=body, timeout=120,
        )
        response.raise_for_status()
        parts = response.json()["candidates"][0]["content"]["parts"]
        text = "".join(p.get("text", "") for p in parts).strip()
        try:
            return json.loads(text[text.find("["):text.rfind("]") + 1])
        except Exception:
            if attempt == 2:
                raise RuntimeError(f"Gemini returned unparsable JSON: {text[:500]}")


def build_products():
    products = []
    for pid, name, cat, brand, price, stock, rating, attrs, desc, lang in ANCHORS:
        products.append({
            "product_id": pid, "name": name, "category": cat, "brand": brand,
            "price_inr": price, "stock": stock, "rating": rating,
            "attributes": attrs, "description": desc, "language": lang,
        })

    next_id = 2000
    for category, target in COUNTS.items():
        have = sum(1 for p in products if p["category"] == category)
        need = target - have
        if need <= 0:
            continue
        prompt = (
            f"Create {need} fictional {category} products for an Indian online "
            f"store called ShopKart. Prices: {PRICE_RANGES[category]}. "
            f"Brands, use only these: {', '.join(BRANDS[category])}. "
            "Vary the product kinds within the category (at least 6 different "
            "kinds). About 8% of descriptions in Hindi (Roman or Devanagari, "
            "everyday Hinglish is fine), the rest in English. Give each product "
            "2-3 attributes from: colour, size, weight (use both '500 g' and "
            "'0.5 kg' styles across products), capacity, storage, ram, battery. "
            "Reply with JSON only: a list of objects, each with name, brand, "
            "price_inr (integer, ending in 9 or 99 where natural), rating "
            "(3.5-4.9, one decimal), attributes (object), description "
            "(one sentence), language (en|hi). No other text, only the JSON list."
        )
        items = call_gemini_json(prompt)
        if len(items) < need:
            raise RuntimeError(
                f"Gemini returned {len(items)} {category} products, needed {need}"
            )
        for item in items[:need]:
            next_id += 1
            # Messiness, applied in code: stock + missing attributes.
            stock = 0 if random.random() < 0.10 else random.randint(1, 40)
            if random.random() < 0.05:
                stock = random.randint(1, 2)
            attrs = dict(item.get("attributes") or {})
            if attrs and random.random() < 0.08:
                attrs.pop(random.choice(list(attrs)))
            products.append({
                "product_id": f"P-{next_id}", "name": item["name"],
                "category": category, "brand": item["brand"],
                "price_inr": int(item["price_inr"]),
                "stock": stock, "rating": round(float(item["rating"]), 1),
                "attributes": attrs, "description": item["description"],
                "language": item.get("language", "en"),
            })
    return products


def build_shoppers(products):
    profiles = call_gemini_json(SHOPPER_PROMPT)
    if len(profiles) != 25:
        raise RuntimeError(f"Gemini returned {len(profiles)} shoppers, needed 25")
    by_category = {}
    for product in products:
        by_category.setdefault(product["category"], []).append(product)
    shoppers = []
    for i, profile in enumerate(profiles, 1):
        sid = f"C-{i:03d}"
        shopper = {
            "shopper_id": sid, "name": profile["name"],
            "preferred_language": profile["preferred_language"],
            "budget_band": profile["budget_band"],
            "taste_tags": profile["taste_tags"], "orders": [],
        }
        if i == 15:  # brand-new shopper, no history
            shopper["orders"] = []
        else:
            pool = [p for cat in shopper["taste_tags"] for p in by_category.get(cat, [])]
            count = 4 if i == 16 else random.randint(3, 5)
            for j, product in enumerate(random.sample(pool, k=count)):
                shopper["orders"].append({
                    "order_id": f"O-{sid}-{j+1}", "product_id": product["product_id"],
                    "ordered_at": f"2026-09-{10 + j:02d}", "qty": 1,
                })
        shoppers.append(shopper)
    # Shopper 18's favourites are now out of stock.
    fav_ids = [o["product_id"] for o in shoppers[17]["orders"]]
    for product in products:
        if product["product_id"] in fav_ids:
            product["stock"] = 0
    return shoppers


